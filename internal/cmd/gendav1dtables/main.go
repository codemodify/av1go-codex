func writeScalarTable(buf *bytes.Buffer, tablesText, cName string, names []string, goName string) {
	block := extractBlock(tablesText, cName)
	values := make([]string, len(names))
	for _, m := range designatedScalar.FindAllStringSubmatch(block, -1) {
		idx := mustIndex(names, m[1], cName)
		values[idx] = translateSymbol(m[2])
	}
	fmt.Fprintf(buf, "var %s = [%d]uint8{", goName, len(names))
	for i, v := range values {
		if i > 0 {
			fmt.Fprint(buf, ", ")
		}
		if v == "" {
			v = "0"
		}
		fmt.Fprint(buf, v)
	}
	fmt.Fprintln(buf, "}")
	fmt.Fprintln(buf)
}

func writeFlatScalarListTable(buf *bytes.Buffer, tablesText, cName string, size int, goName string) {
	block := extractBlock(tablesText, cName)
	start := strings.Index(block, "{")
	end := strings.LastIndex(block, "}")
	if start < 0 || end < 0 || end <= start {
		fatalf("%s: malformed scalar list", cName)
	}
	content := regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(block[start+1:end], "")
	parts := splitCSV(content)
	if len(parts) != size {
		fatalf("%s: list size = %d, want %d", cName, len(parts), size)
	}
	fmt.Fprintf(buf, "var %s = [%d]uint8{", goName, size)
	for i, part := range parts {
		if i > 0 {
			fmt.Fprint(buf, ", ")
		}
		fmt.Fprint(buf, translateSymbol(part))
	}
	fmt.Fprintln(buf, "}")
	fmt.Fprintln(buf)
}

