func writeRowTable(buf *bytes.Buffer, tablesText, cName string, names []string, rowLen int, goName string) {
	block := extractBlock(tablesText, cName)
	rows := make([][]string, len(names))
	for _, m := range designatedRow.FindAllStringSubmatch(block, -1) {
		idx := mustIndex(names, m[1], cName)
		parts := splitCSV(m[2])
		row := make([]string, rowLen)
		for i := 0; i < rowLen && i < len(parts); i++ {
			row[i] = translateSymbol(parts[i])
		}
		rows[idx] = row
	}

	fmt.Fprintf(buf, "var %s = [%d][%d]uint8{\n", goName, len(names), rowLen)
	for _, row := range rows {
		fmt.Fprint(buf, "{")
		for i := 0; i < rowLen; i++ {
			if i > 0 {
				fmt.Fprint(buf, ", ")
			}
			v := "0"
			if i < len(row) && row[i] != "" {
				v = row[i]
			}
			fmt.Fprint(buf, v)
		}
		fmt.Fprintln(buf, "},")
	}
	fmt.Fprintln(buf, "}")
	fmt.Fprintln(buf)
}

func extractSection(text, marker, nextMarker string) string {
	start := strings.Index(text, marker)
	if start < 0 {
		fatalf("marker %q not found", marker)
	}
	start += len(marker)
	end := strings.Index(text[start:], nextMarker)
	if end < 0 {
		fatalf("next marker %q not found after %q", nextMarker, marker)
	}
	return text[start : start+end]
}

func extractBlock(text, marker string) string {
	start := strings.Index(text, marker)
	if start < 0 {
		fatalf("marker %q not found", marker)
	}
	start = strings.Index(text[start:], "{") + start
	if start < 0 {
		fatalf("open brace not found after %q", marker)
	}
	depth := 0
	for i := start; i < len(text); i++ {
		switch text[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return text[start : i+1]
			}
		}
	}
	fatalf("unclosed block for %q", marker)
	return ""
}

func extractField(text, marker, nextMarker string) string {
	if nextMarker == "" {
		return extractBlock(text, marker)
	}
	return extractSection(text, marker, nextMarker)
}

func extractIndexedBlocks(text, marker string, count int) []string {
	block := extractBlock(text, marker)
	re := regexp.MustCompile(`\[(\d+)\]\s*=\s*\{`)
	matches := re.FindAllStringSubmatchIndex(block, -1)
	if len(matches) != count {
		fatalf("%s block count = %d, want %d", marker, len(matches), count)
	}
	blocks := make([]string, count)
	for _, m := range matches {
		idx := mustAtoi(block[m[2]:m[3]])
		if idx < 0 || idx >= count {
			fatalf("%s index out of range: %d", marker, idx)
		}
		open := m[1] - 1
		depth := 0
		end := -1
		for i := open; i < len(block); i++ {
			switch block[i] {
			case '{':
				depth++
			case '}':
				depth--
				if depth == 0 {
					end = i + 1
				}
			}
			if end >= 0 {
				break
			}
		}
		if end < 0 {
			fatalf("%s index %d: unclosed block", marker, idx)
		}
		blocks[idx] = block[open:end]
	}
	return blocks
}

func parseCDFValues(list string) []uint16 {
	parts := splitCSV(list)
	out := make([]uint16, 0, len(parts))
	for _, part := range parts {
		v := mustAtoi(part)
		out = append(out, uint16(32768-v))
	}
	return out
}

func formatUint16Array(vals []uint16, size int) string {
	var parts []string
	for _, v := range vals {
		parts = append(parts, strconv.Itoa(int(v)))
	}
	for len(parts) < size {
		parts = append(parts, "0")
	}
	return fmt.Sprintf("[%d]uint16{%s}", size, strings.Join(parts, ", "))
}

func splitCSV(s string) []string {
	raw := strings.Split(s, ",")
	out := make([]string, 0, len(raw))
	for _, part := range raw {
		part = strings.TrimSpace(strings.Trim(part, "{}"))
		if part == "" {
			continue
		}
		out = append(out, part)
	}
	return out
}

func translateSymbol(s string) string {
	s = strings.TrimSpace(s)
	if n, err := strconv.Atoi(s); err == nil {
		return strconv.Itoa(n)
	}
	if idx, ok := txSizeIndex[s]; ok {
		return strconv.Itoa(idx)
	}
	if idx, ok := intraModeIndex[s]; ok {
		return strconv.Itoa(idx)
	}
	fatalf("unmapped symbol %q", s)
	return ""
}

func mustIndex(list []string, name, kind string) int {
	for i, v := range list {
		if v == name {
			return i
		}
	}
	fatalf("%s entry %q not found", kind, name)
	return -1
}

func mustAtoi(s string) int {
	v, err := strconv.Atoi(strings.TrimSpace(s))
	if err != nil {
		fatalf("parse int %q: %v", s, err)
	}
	return v
}

func readFile(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		fatalf("read %s: %v", path, err)
	}
	return string(b)
}

