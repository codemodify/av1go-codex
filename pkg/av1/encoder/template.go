package encoder

import "github.com/codemodify/av1go-codex/pkg/container/mp4"

var (
	black16x16AV1C = []byte{
		0x81, 0x00, 0x0c, 0x00,
		0x0a, 0x06, 0x18, 0x0c, 0xff, 0xda, 0x00, 0x80,
	}
	black16x16Sample = []byte{
		0x0a, 0x06, 0x18, 0x0c, 0xff, 0xda, 0x00, 0x80,
		0x32, 0x0c, 0x18, 0x00, 0x00, 0x00, 0x50, 0x00,
		0x00, 0x00, 0xa9, 0x8e, 0x58, 0xd4,
	}
)

func black16x16CodecConfig() mp4.AV1CodecConfig {
	return mp4.AV1CodecConfig{Raw: append([]byte(nil), black16x16AV1C...)}
}

func black16x16SampleData() []byte {
	return append([]byte(nil), black16x16Sample...)
}
